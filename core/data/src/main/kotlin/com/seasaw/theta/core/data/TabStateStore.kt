package com.seasaw.theta.core.data

import android.content.Context
import com.seasaw.theta.core.common.IoDispatcher
import dagger.hilt.android.qualifiers.ApplicationContext
import java.io.File
import java.io.IOException
import javax.inject.Inject
import javax.inject.Singleton
import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.withContext

/**
 * Saved WebView state for regular tabs, stored as files because a tab's state can outgrow what fits comfortably in a
 * database row. State is a cache: losing it only means the tab reloads its URL, so IO failures are not surfaced.
 * Incognito state must never come here.
 */
@Singleton
class TabStateStore @Inject constructor(
    @ApplicationContext context: Context,
    @IoDispatcher private val dispatcher: CoroutineDispatcher,
) {
    private val directory = File(context.filesDir, "tab_state")

    suspend fun write(tabId: String, state: ByteArray) = withContext(dispatcher) {
        try {
            directory.mkdirs()
            val temporary = File(directory, "$tabId.tmp")
            temporary.writeBytes(state)
            temporary.renameTo(fileFor(tabId))
        } catch (ignored: IOException) {
            false
        }
        Unit
    }

    suspend fun read(tabId: String): ByteArray? = withContext(dispatcher) {
        try {
            fileFor(tabId).takeIf { it.exists() }?.readBytes()
        } catch (ignored: IOException) {
            null
        }
    }

    suspend fun delete(tabId: String) = withContext(dispatcher) {
        fileFor(tabId).delete()
        Unit
    }

    suspend fun clear() = withContext(dispatcher) {
        directory.deleteRecursively()
        Unit
    }

    /** Tab ids are generated by us, but the path is still confined in case one ever arrives from elsewhere. */
    private fun fileFor(tabId: String): File = File(directory, File(tabId).name)
}
